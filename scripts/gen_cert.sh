#!/usr/bin/env bash
# G5 (Student A): self-signed localhost certificate for TLS termination.
# Raw PEM files stay outside Git (certs/ is gitignored); the rendered fragment
# embeds them as a DEMO certificate so `kong config parse` works out of the box.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/certs"
FRAGMENT="$ROOT/kong/fragments/50-tls.yml"
mkdir -p "$OUT"
if ! command -v openssl >/dev/null 2>&1; then
  echo "openssl not found; add real OpenSSL (Git for Windows usr/bin) to PATH" >&2
  exit 1
fi

# Git Bash path-converts /CN=... unless MSYS_NO_PATHCONV is set, while the
# Windows OpenSSL binary needs native paths for its output files.
OUT_WIN="$(cygpath -w "$OUT" 2>/dev/null || echo "$OUT")"
FRAGMENT_WIN="$(cygpath -w "$FRAGMENT" 2>/dev/null || echo "$FRAGMENT")"
MSYS_NO_PATHCONV=1 openssl req -x509 -newkey rsa:2048 -nodes -sha256 -days 365 \
  -subj "/CN=localhost/O=FinTech Gateway Demo" \
  -addext "subjectAltName=DNS:localhost,IP:127.0.0.1" \
  -keyout "$OUT_WIN/localhost.key" \
  -out "$OUT_WIN/localhost.crt" 2>/dev/null

PYTHON_BIN="${PYTHON:-python3}"
if ! command -v "$PYTHON_BIN" >/dev/null 2>&1; then
  PYTHON_BIN="python"
fi
"$PYTHON_BIN" - "$OUT_WIN/localhost.crt" "$OUT_WIN/localhost.key" "$FRAGMENT_WIN" <<'PY'
import sys
from pathlib import Path

cert = Path(sys.argv[1]).read_text(encoding="utf-8").strip()
key = Path(sys.argv[2]).read_text(encoding="utf-8").strip()
target = Path(sys.argv[3])

cert_id = "11111111-1111-1111-1111-111111111111"
lines = [
    "# G5 (Student A) - TLS termination (G5, R15).",
    "# DEMO self-signed certificate (CN=localhost, SAN localhost + 127.0.0.1).",
    "# Generated by scripts/gen_cert.sh; upstream traffic stays plain HTTP.",
    "# Kong listens on :8443 with `ssl`; SNI selects this certificate.",
    "certificates:",
    "  - id: " + cert_id,
    "    cert: |",
]
lines += ["      " + line for line in cert.splitlines()]
lines += ["    key: |"]
lines += ["      " + line for line in key.splitlines()]
lines += [
    "snis:",
    "  - name: localhost",
    "    certificate: " + cert_id,
]
target.write_text("\n".join(lines) + "\n", encoding="utf-8")
PY

echo "generated $FRAGMENT from $OUT/localhost.crt (demo only)"
