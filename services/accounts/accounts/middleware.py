"""
Gateway header and logging middleware (V1.3).

Kong adds these request headers before forwarding:
  Kong-Request-ID      correlation id generated by the correlation-id plugin
  X-Consumer-Username  authenticated Kong consumer (fintech-free / premium)

The middleware:
  1. stores them on the request for downstream views;
  2. echoes them on the response so a client can correlate Kong, the service
     log and the response (evidence item 08);
  3. adds X-Served-By = container hostname, which proves which replica
     answered (needed for the two-replica load-balancing evidence);
  4. writes one structured log line per request.
"""

import logging
import socket
import uuid

from django.utils.deprecation import MiddlewareMixin

logger = logging.getLogger("accounts.gateway")


class GatewayHeadersMiddleware(MiddlewareMixin):
    def process_request(self, request):
        request.kong_request_id = request.headers.get("Kong-Request-ID", "")
        request.kong_consumer = request.headers.get("X-Consumer-Username", "")
        # A local call (no Kong) still gets a correlation id for its log.
        request.local_request_id = request.kong_request_id or uuid.uuid4().hex
        return None

    def process_response(self, request, response):
        served_by = socket.gethostname()
        response["X-Served-By"] = served_by

        request_id = getattr(request, "kong_request_id", "")
        if request_id:
            response["Kong-Request-ID"] = request_id

        consumer = getattr(request, "kong_consumer", "")
        if consumer:
            response["X-Consumer-Username"] = consumer

        logger.info(
            "method=%s path=%s status=%s served_by=%s request_id=%s consumer=%s",
            request.method,
            request.path,
            response.status_code,
            served_by,
            getattr(request, "local_request_id", "-"),
            consumer or "-",
        )
        return response
